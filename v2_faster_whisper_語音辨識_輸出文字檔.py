def convertNewLineFormat(filename) :
  if os.path.exists(filename) :
    f = open(filename, 'r+', encoding="utf-8")
    data = f.read()
    data = re.sub('\r', '', data, flags=re.MULTILINE) #remove all \r
    data = re.sub('\n', '\r\n', data, flags=re.MULTILINE) #replace \n to \r\n
    f.seek(0)
    f.write(data)
    f.truncate()
    f.close()

